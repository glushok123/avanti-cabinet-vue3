/**
 * Типы переключателя шагов мастера (`avanti_tabs`).
 * В макете это полоса «1. IBAN / 2. COMMISSIONE / 3. COORDINATE»
 * в шапке модального окна комиссии.
 */

/**
 * Состояние шага, не зависящее от того, какой шаг открыт прямо сейчас.
 * Текущий шаг задаётся через `v-model` и вычисляется отдельно, поэтому
 * значения ниже описывают только прогресс и доступность:
 * - `done` — шаг пройден, на него можно вернуться;
 * - `available` — шаг доступен, но ещё не пройден (значение по умолчанию);
 * - `locked` — шаг недоступен: переключиться на него нельзя.
 */
export type AvantiTabState = 'done' | 'available' | 'locked'

/**
 * Половина сегментированного переключателя экранов (`avanti_segmented_nav`).
 * В отличие от шага мастера у неё нет состояния и панели с содержимым:
 * это ссылка на соседний экран, а не вкладка внутри текущего.
 */
export interface AvantiSegmentedNavItem {
  /** Идентификатор экрана — уходит наружу в событии `select`. */
  id: string
  /** Видимая подпись («Crea account»). */
  label: string
}

/** Один шаг-вкладка в полосе переключателя. */
export interface AvantiTabItem {
  /** Идентификатор шага — именно он уходит наружу через `v-model`. */
  id: string
  /** Видимая подпись («1. IBAN»). */
  label: string
  /** Прогресс и доступность шага. По умолчанию — `available`. */
  state?: AvantiTabState
  /**
   * Идентификатор DOM-элемента панели с содержимым шага.
   * Если задан, вкладка получает `aria-controls="<panelId>"`
   * и собственный `id="<panelId>-tab"` — его панель указывает
   * в `aria-labelledby`, чтобы связка tab ↔ tabpanel была полной.
   */
  panelId?: string
}
