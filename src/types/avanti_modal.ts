/**
 * Публичный контракт базового модального окна (`avanti_modal`).
 * Оболочку переиспользуют все модалки макета — комиссия, документы,
 * подпись договора, авторизация, настройки аккаунта, — поэтому пропы
 * и события описаны здесь, а не в компоненте.
 */

/**
 * Ширина окна на десктопе.
 * В найденных кадрах макета встречается только `md` — 681px
 * («Модальное окно — Комиссия» 681×761 и «Модальное окно — Координаты» 681×864).
 * `sm` (480px) и `lg` (880px) добавлены с запасом под другие сценарии.
 */
export type AvantiModalSize = 'sm' | 'md' | 'lg'

/**
 * Оформление окна.
 * - `default` — окна мастера комиссии: обводка, круглая кнопка закрытия,
 *   ширина из пропа `size`;
 * - `brand` — узкие окна авторизации и настроек аккаунта (кадры 0:1235,
 *   0:1338, 1:2773, 1:2997, 1:3226): 350px на мобильной и 524px на десктопе,
 *   без обводки, шапка «пусто — логотип — крестик» и крестик без подложки.
 *   В этом варианте проп `size` не участвует: ширина задана кадрами.
 */
export type AvantiModalVariant = 'default' | 'brand'

/** Чем вызвано закрытие окна — приходит полезной нагрузкой в событии `close`. */
export type AvantiModalCloseReason =
  /** Нажата круглая кнопка закрытия в шапке. */
  | 'button'
  /** Клик по затемнению за пределами окна. */
  | 'backdrop'
  /** Нажата клавиша Escape. */
  | 'escape'

/** Пропы `avanti_modal`. */
export interface AvantiModalProps {
  /** Окно открыто. Работает и как `v-model:open`, и как обычный проп. */
  open: boolean
  /** Крупный заголовок окна. Он же становится доступным именем диалога. */
  title?: string
  /** Малая бирюзовая надпись над заголовком («Sotto-etichetta» в макете). */
  eyebrow?: string
  /** Доступное имя диалога, когда заголовок не выводится (`title` пуст). */
  label?: string
  /** Ширина окна на десктопе. По умолчанию `md` — размер из макета. */
  size?: AvantiModalSize
  /** Оформление окна. По умолчанию `default` — окна мастера комиссии. */
  variant?: AvantiModalVariant
  /** Показывать круглую кнопку закрытия в шапке. По умолчанию да. */
  closable?: boolean
  /** Закрывать окно кликом по затемнению. По умолчанию да. */
  closeOnBackdrop?: boolean
  /** Закрывать окно клавишей Escape. По умолчанию да. */
  closeOnEscape?: boolean
  /** Доступное имя кнопки закрытия. */
  closeLabel?: string
}

/** События `avanti_modal`. */
export interface AvantiModalEmits {
  /** Половина `v-model:open`: окно просит себя закрыть. */
  'update:open': [value: boolean]
  /** То же закрытие, но с причиной — для сценариев вроде «подтвердить выход». */
  close: [reason: AvantiModalCloseReason]
}
